"""业务错误码表。约定： - 0 表示成功（与 DRF/HTTP 无关）。
- >= 1000 为业务失败；HTTP 状态码保持 200，由调用方读 code 分支。 - 传输与认证层失败不使用本表，直接沿用 HTTP 状态码作为 code 值。本表随业务扩展（订单、派单、结算各有专属码段），扩展时在此登记并保持唯一。
新码按段取号、集中登记，不要各取各的。
"""
from enum import IntEnum


class ErrorCode(IntEnum):
    OK = 0
    VALIDATION = 1000
    CONFLICT = 1001
    BUSINESS = 1002
    LAST_ADMIN = 1003
    SELF_LOCKOUT = 1004
    # ── P3 派单 / 抢单 ──
    # `1013` 共用一个码：用户看到的都是「你现在抢不了」。支数不是契约，
    # 清单在 `check_grab_limits`；调用方靠 msg 区分原因。
    ORDER_ALREADY_TAKEN = 1012        # 订单已被接走（条件更新 rowcount == 0）
    GRAB_LIMIT_EXCEEDED = 1013        # 不满足抢单限制（NULL 价 / 未实名 / 禁自助接单 / 价格区间 / 接单上限）
    PERFORMANCE_STATE_INVALID = 1014  # 绩效状态不允许此操作
    # ── P4 结算与财务 ──
    SETTLE_STATE_INVALID = 1006       # 绩效状态不允许结账（不存在/不可见/已结清/
    #                       订单未完成/没有接单人/状态不允许，或并发改动）。
    #                       结账不看审核状态；具体拒绝句在 settlement 的拒绝文案里。
    REFUND_STATE_INVALID = 1007       # 订单状态不允许部分退款（要求 COMPLETED，spec §5.1 #2）
    REFUND_AMOUNT_INVALID = 1008      # 退款额非法（≤ 0 / 超过剩余可退额，spec §5.1 #3#4）
    COMMISSION_NOT_CONFIGURED = 1009  # 客服行的 commission_rate 为空 → 拒绝整笔退款（spec §4.5 细节 3）
    REFUND_DUPLICATE_REQUEST = 1010   # request_id 已被用过（幂等兜底）。
    #                       退款表与绩效调整表各管各的唯一约束，不是全局键。
    #                       名字里的 REFUND 是引入时的叫法，语义就是「这个请求号用过了」。
    SETTLE_NEGATIVE_PAYABLE = 1011    # 应付净额为负 → 拒绝结账（spec §3.3 / §4.3 第 4 步）
    # ── 平台店铺对接 / 录单读单（阿奇索线占 1015–1017；闲管家线 **复用同一批**）── ⚠️ 这三个码是**跨平台**的：阿奇索（`apps/business/agiso.py`）与闲管家（`apps/business/xgj.py`）
    # 共用它们。判据一律是「**上游类别**」，不是「上游返回了哪个数字」——两个平台的码完全不可比（阿奇索鉴权错是 `Error_Code == 1`，闲管家是 `code == 100001`，而且后者一个码管四种原因）。
    PLATFORM_NOT_CONFIGURED = 1015   # 该来源没有可用的店铺对接配置（阿奇索/闲管家两边都不可用），
    #                      或所需凭据为空（阿奇索：平台级 AppId/Secret 或授权码；
    #                      闲管家：该行的 AppKey/AppSecret）
    PLATFORM_TOKEN_INVALID = 1016    # 上游**凭据或时钟**类失败 —— 阿奇索 `Error_Code == 1`
    #                      （实测原文 "Invalid access token"）；
    #                      闲管家 `code == 100001`（实测：AppID 无效 / 签名错 /
    #                      时间戳超出 5 分钟 / 缺 AppID **四种都回它**）
    PLATFORM_QUERY_FAILED = 1017     # 上游其它失败 / 网络异常（判据是「不属于上一类」，不枚举上游码）
    # ── 上下游订单互通（spec §9-S5 / §8；`1000–1017` 已占，本线从 1018 起）──────────
    # ⚠️ 认证失败**不走这些码**：令牌无效一律是 HTTP **401**（spec D8），不是业务码。
    PEER_BIND_FAILED = 1018     # 绑定握手失败：账号密码不对 / 对端不可达 / 对端拒绝。
    #                  ⚠️ 「账号不存在」与「密码错」**回同一个码与同一句 msg**
    #                  （spec §9-S5：不给账号枚举面）。
    PEER_NOT_BOUND = 1019       # 本租户还没有可用的绑定（例如解绑后又去推单）
    PEER_REJECTED = 1020        # 对端拒收：令牌无效 / 绑定已被解除 / 载荷不合法
    PEER_UNREACHABLE = 1021     # 网络层失败：超时 / DNS / 连接被拒 / 非 JSON 响应
    # ── 录单页「快速指派」（业务方裁定；决策 D-0179）──────────────────── ⚠️ 它**不是**一条普通失败：`POST /orders/` 带 `assignee` 时，单**已经建好并落库**，只有「指派」这一步没成 ⇒ 调用方必须能把这一档与「什么都没发生」区分开
    # （分不清的话，用户再点一次保存就是**又建一张单**）。 `data` = `{"order_no", "reason", "assign_code"}`（见 `OrderViewSet.create`）。 ⛔ 不许把这一档退回 `1002` / 其它既有码：那样页面分不清「建了单、没指派」与「请求被拒」。
    ORDER_CREATED_ASSIGN_FAILED = 1022  # 订单已建好，指派未成功（订单**不回滚**）
    # ── 录单页「内部抢单」（业务方裁定；本线 `feat/hall-throw-autorefresh`）── ⚠️ 与上一档**同一形状、同一理由**：`throw_to_hall=true` 时建单照旧提交，只有「把这张单抛进内部抢单大厅」这一步没成 ⇒ 调用方必须能把这一档与
    # 「请求被拒、什么都没发生」区分开（分不清的话，用户再点一次保存就是**又建一张单**）。 `data` = `{"order_no", "reason"}`（见 `OrderViewSet.create`）。 ⛔ 只接 `IllegalTransition`（可预期的域层拒绝）；**其它**异常不许被翻译成这个码，
    # 未预期的照旧响亮 500（E-0010：把未预期异常伪装成业务结果会让监控失明）。
    ORDER_CREATED_THROW_FAILED = 1023  # 订单已建好，抛入内部抢单大厅未成功（订单**不回滚**）
    # ── 开放平台对外 API v2（`1018`–`1023` 已占，本段从 `1024` 起）────────────── ⚠️ 这一档**不是**"暂时失败"、⛔ 也**不是**"查不到"：它是「**暂不实现**」的那条路径——业务方裁定「接单排行榜不做」（设计文档 §13.10-1），
    # 但**路径保留**、恒回这个码 + 一句人话（`RANKS_NOT_AVAILABLE_MSG`）， HTTP 仍是 **200**（本仓口径：业务结果由 `code` 表达）。 ⛔ **不许拿既有码顶替**：`1002` 会被第三方读成"查不到"、`1000` 会被读成"你参数写错了"
    # ⇒ 两种都会让人去改一个**没错**的地方；说破「尚未开放」才是这一档的语义。
    OPENAPI_RANKS_NOT_AVAILABLE = 1024  # 对外「接单排行榜」尚未开放（暂不实现，路径保留）
    # ── 实名认证（业务方裁定；`1018`–`1024` 已占，本段从 `1025` 起）──────── ⚠️ 这三个码**不是**「暂时失败」：它们各自对应一条**确定的业务拒绝**，
    # 必须能让调用方区分「功能没开」「租户没次数」「平台没包」——混成一个码会让管理员去改一个**没错**的地方（同族：`OPENAPI_RANKS_NOT_AVAILABLE` 的注释）。
    REALNAME_DISABLED = 1025        # 本租户未启用实名认证功能（RealNameSetting.enabled=False）
    REALNAME_QUOTA_EXHAUSTED = 1026  # 本租户实名认证余量不足（granted 用尽，或压根没有额度行）
    REALNAME_NO_PACKAGE = 1027      # 平台侧没有可用的实名密钥包（全部停用/耗尽/过期）

    # ── 平台订单状态类拒绝（线 F：闲管家录单识别拒「待付款」）────────────── 这一档管的是：**上游订单自己的状态**让本次「读取订单」被拒（今天唯一一档 = 闲管家的 11「待付款」，由一个系统开关控制，默认开）。判据是**上游订单状态**本身，⛔ **不是**上游返回了哪个数字——与 `1015`–`1017` 那条「跨平台共用、判据是**上游类别**」同款：`1016`/`1017` 量的是「上游这次调用成不成功」，本码量的是「上游这次调用成功、但它给的订单状态不允许录单」。 ⛔ 不许拿既有码顶替（同 `1024` 那条的理由）：
    # - `1002`（BUSINESS）是"业务失败"的兜底，用它排障时分不清「被开关拦的 / 单号写错了 / 上游拒的」； - `1000`（VALIDATION）会被读成"你请求参数写错了"⇒ 让人去改一个**没错**的地方； - `1015`–`1017` 都会被读成"上游那边出了问题"⇒ 让人去查凭据 / 重试，而这张单重试一万次也还是待付款。 ⚠️ **前端按码分支**：录单页（`order-addorder.ts`）把本码放进了「读单失败要开口」的集合（`SPEAKING_READ_ORDER_CODES` = `1015` ∪ `1028`）⇒ 本码的 `msg` 会**原样弹给录单的人**。 ⛔ 那么它必须是一句**拿到它的人做得到**的话（别写"去某个他进不去的页面改设置"）。
    # ⚠️ 它**不**镜像进前端 `@/config/errorCodes`：那一份只收"页面真有分支的那几个 code"，录单页的分支判据就是上面那个集合（评审 裁定），不另立第二处数字出处。
    PLATFORM_ORDER_STATUS_REJECTED = 1028  # 上游订单状态不允许录单识别（今天 = 闲管家 11「待付款」，
    #                            由系统开关 `reject_unpaid_xgj_order` 控制）

    # ── 实名核验按人限流（D-0251；`1025`–`1028` 已占，本段从 `1029` 起）──── ⚠️ 与 `1025`–`1027` 同一条纪律：这一档是一条**确定的业务拒绝**，⛔ 不许拿既有码顶替—— `1026`（租户余量不足）会让人去催客服**买次数**、`1000` 会让人去改一个**没写错**的号码、
    # `1002` 什么都不说 ⇒ 混用任何一个都会让人去改一个没错的地方。 ⚠️ 判据形态照 `1026`/`1027` 的先例：业务码 + 一句人话；超额**不锁定**、窗口滚过自动恢复（口径与实现：`apps/realname/rate_limit.py`）。
    REALNAME_RATE_LIMITED = 1029     # 同一用户实名核验提交过于频繁（默认 3 次/天；业务方从 D-0251 的 5 次/小时改来）

    # ── QQ 机器人（`feat/qqbot-line` ；`1030` 起为本线码段）────────── ⚠️ 同一条纪律：这是一条**确定的业务拒绝**（本租户还没配机器人凭据），⛔ 不许拿既有码顶替——`1002` 说不出「去把机器人配好」这件事、`1015`（平台未配置）量的是**店铺对接**那几行
    # 配置、混用会把人引去查错误的页面。代理类端点（菜单 / 禁言 / 入群申请 / 分享链接）在 `QQBotBinding.get_solo()` 无 `app_id` 或无 `app_secret` 时统一回它（HTTP 仍 200）。
    QQBOT_NOT_CONFIGURED = 1030     # 机器人未配置：先在 QQ 机器人设置页填 AppID / AppSecret

    # ── 打手 App 认证（`feat/taker-app`；`1031` 起为本线码段）────────────
    # ⚠️ 同一条纪律：两条都是**确定的业务拒绝**，⛔ 不许拿既有码顶替——
    # `1029`（实名核验限流）属于另一个域；`1000`（校验失败）说不出「等一下再发」。
    APP_SMS_RATE_LIMITED = 1031     # 短信验证码发得太频繁（同号 60 秒 / 同 IP 24 小时额度）
    APP_SMS_CODE_INVALID = 1032     # 验证码错误、已过期或已使用（三种对外同一文案，防探测）

    # ── 打手 App 开放注册（`feat/taker-app-register`；`1033` 起）────────── ⚠️ 同一条纪律：这是一条**确定的业务拒绝**，⛔ 不许拿既有码顶替—— `1031` 量的是「短信发得太频繁」（本端点**不发短信**）、`1029` 是实名核验的按人限流、
    # `1000` 会被读成「你手机号/密码写错了」⇒ 都会把人引去改一个**没错**的地方。 ⚠️ 「手机号已被占用」**不新开码**：那是 `1001 CONFLICT` 的既有语义（自助注册线的 IntegrityError 兜底也回它），换码只会让两处「已注册」说两种话。
    APP_REGISTER_RATE_LIMITED = 1033  # 同一来源 IP 的注册尝试过于频繁（默认 60 次/小时）

    # 兼容仍运行旧登录逻辑的上家。当前网页登录口不再因账号来源返回此码。
    APP_ACCOUNT_WEB_LOGIN_FORBIDDEN = 1034

    # ── 打手「我的收入」/ 提前结算申请（`1035` 起为本线码段）──────────── ⚠️ 同一条纪律：两条都是**确定的业务拒绝**，⛔ 不许拿既有码顶替—— `1006`（结账状态不允许）量的是**财务结账**那条路（它连"是谁"都未必对得上），
    # `1000` 会被读成「你请求参数写错了」（而参数本身没错：这个绩效就是不能申请）； `1002` 什么都不说。混用会让人去改一个没错的地方。 ⚠️ 两条分开的理由：**额度用完**是「你已经申请过 3 次了」这件**人身上**的事，
    # 其余拒绝是「这一行现在不能申请」这件**单上**的事；合成一个码，页面就没法给出「额度用完了」那句该说的话（spec §3.4 规则 1 的额度是独立规则）。
    EARLY_SETTLE_INVALID = 1035       # 该绩效不能申请提前结算（不存在 / 不是我的 /
    #                       不是「打单工资」/ 订单未完成 / 已结账 / 已申请过）
    EARLY_SETTLE_LIMIT_EXCEEDED = 1036  # 提前结算申请额度已用完（`settings.EARLY_SETTLE_LIMIT`）

    # ── 订单管理页「同步收款」（`feat/receipt-sync`；`1037` 起为本线码段）─── ⚠️ 这是**确定的业务拒绝**（另一轮同步收款正在跑、本次一个上游请求都没发）， ⛔ 不许拿既有码顶替：`1000` 会被读成「日期写错了」（而参数完全没错）、
    # `1010` 已被「重复退款请求」占用且前端有专门分支、`1007` 语义不同。判据 = 请求线程用**自己的连接** `pg_try_advisory_lock` 试拿失败（领域模块 `apps/business/xgj_receipt_sync.py::sync_is_running`）；⛔ 不是进程内闸门
    # （生产是 gunicorn `--workers 2`，进程内闸门挡不住另一台 worker）。
    XGJ_RECEIPT_SYNC_BUSY = 1037      # 另一轮同步收款正在运行（请稍后再试）

    # ── 登录口温和限流（`fix/login-ratelimit`；`1038` 起为本线码段）───── ⚠️ 同一条纪律：这是一条**确定的业务拒绝**（「现在别来」，不是「凭据错」）， ⛔ 不许拿既有码顶替——`1000` 会被读成「你用户名/密码写错了」⇒ 让人去改一个**没错**的输入；
    # 与凭据错共用同一个码，则「被限流」与「密码错」不可分辨，爆破者反而拿到等价信号、被限流的正常人会去反复试改密码。文案三口共用一句固定话（`apps/core/login_rate_limit.RATE_LIMITED_MSG`），⛔ 不含任何「账号存在」信息。
    # 口径：D-0332（三个登录口 = 主登录 / App 密码登录 / 公众号绑定页登录）。
    LOGIN_RATE_LIMITED = 1038         # 该来源 IP / 该账号的登录失败过于频繁，暂时拒绝

    # ── 企微自建应用（D-0379；`1039` 起为本线码段）──────────── ⚠️ 同一条纪律：两条都是**确定的业务结果**，⛔ 不许拿既有码顶替——
    # `1015`（平台未配置）量的是**店铺对接**那几行配置、混用会把人引去查错误的页面；
    # `1000` 会被读成「你参数写错了」；`1002` 什么都不说。
    WECOM_NOT_CONFIGURED = 1039       # 企微应用（或客户联系）未配置 / 未启用：先到设置页填凭据
    WECOM_REMOTE_FAILED = 1040        # 企微侧调用失败（errcode 与人话在 msg 里；⛔ 不是本仓参数错）
