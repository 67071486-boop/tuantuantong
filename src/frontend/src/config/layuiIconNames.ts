export type LayuiIconName = keyof typeof LAYUI_ICON_CODE_POINTS

/** 有**字体字形**的图标名：把码点为 `null` 的名字排除掉（官方 CSS 里那些 `content:''`、
 *  靠 CSS 画出来的记号，如 `indeterminate`）。映射表与 `<AppIcon>` 用这个类型，
 *  于是「在映射表之外把没有字形的名字当图标用」也会**编译不过**，而不是等到屏幕上没有图形。
 *  从上面那张表**派生**，不写死具体名字：官方包将来多/少一个 `null` 都跟着变。
 *  ⚠️ 本文件是生成文件——表体由头注里的脚本产出，这一行类型是手写的，重新生成后要照抄回来。 */
export type GlyphIconName = {
  [K in LayuiIconName]: (typeof LAYUI_ICON_CODE_POINTS)[K] extends null ? never : K
}[LayuiIconName]

/** 注册表里的全部名字（从上面那张表派生，保持单一出处）。 */
export const LAYUI_ICON_NAMES: readonly string[] = Object.keys(LAYUI_ICON_CODE_POINTS)

/** 按名字取码点（`null` = 该名字在官方 CSS 里不是字体字形，别拿它当菜单图标）。
 *  收窄到 `LayuiIconName` 是刻意的：字面量键对象在 `noUncheckedIndexedAccess` 下不能直接用 `string` 查。 */
export function layuiIconCodePoint(name: LayuiIconName): string | null {
  return LAYUI_ICON_CODE_POINTS[name]
}
