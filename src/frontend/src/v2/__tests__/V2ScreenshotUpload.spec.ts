// @vitest-environment jsdom
import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
const api = vi.hoisted(() => ({ fetch: vi.fn(), ticket: vi.fn(), claim: vi.fn(), put: vi.fn(), compress: vi.fn() }))
vi.mock('@/api/screenshots', () => ({ fetchScreenshots: api.fetch, requestScreenshotTicket: api.ticket, claimScreenshot: api.claim }))
vi.mock('@/layui-island/directUpload', () => ({ putFileToStorage: api.put }))
vi.mock('@/layui-island/imageCompress', () => ({ MAX_UPLOAD_BYTES: 18 * 1024 * 1024, COMPRESSED_MAX_BYTES: 5 * 1024 * 1024, compressImage: api.compress }))
import V2ScreenshotUpload from '../V2ScreenshotUpload.vue'
const no = '20261113000000000001'
const image = (name: string) => new File(['image'], name, { type: 'image/png' })
describe('V2 截图上传', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    api.fetch.mockResolvedValue({ items: [] })
    api.ticket.mockResolvedValue({ screenshot_id: 4, upload_url: '/upload' })
    api.put.mockResolvedValue(undefined)
    api.claim.mockResolvedValue(undefined)
    api.compress.mockImplementation(async (file: File) => file)
    URL.createObjectURL = vi.fn(() => 'blob:preview')
    URL.revokeObjectURL = vi.fn()
  })
  it('拖入订单截图后直传，保存时带备注认领', async () => {
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await flushPromises()
    await wrapper.trigger('drop', { dataTransfer: { files: [image('order.png')] } })
    await flushPromises()
    expect(api.ticket).toHaveBeenCalledWith(no, 'png', 0)
    expect(api.put).toHaveBeenCalledWith('/upload', expect.any(File))
    expect(wrapper.text()).toContain('上传成功（等待保存）')
    await wrapper.get('input[placeholder="可以给图片做个备注说明"]').setValue('进度说明')
    await wrapper.get('.shot-save').trigger('click')
    await flushPromises()
    expect(api.claim).toHaveBeenCalledWith(no, { screenshot_id: 4, original_name: 'order.png', remark: '进度说明' })
    expect(wrapper.text()).toContain('保存成功')
    expect(wrapper.text()).not.toContain('order.png')
    wrapper.unmount()
  })
  it('粘贴二维码，保存失败保留待保存项', async () => {
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await flushPromises()
    await wrapper.get('input[value="1"]').setValue()
    expect(wrapper.get('.shot-paste').attributes('contenteditable')).toBe('true')
    expect(wrapper.get('.shot-paste').attributes('aria-label')).toBe('点击此处后，可以使用快捷键 Ctrl+V 直接粘贴图片上传')
    const file = image('qr.png')
    await wrapper.get('.shot-paste').trigger('paste', { clipboardData: { items: [{ kind: 'file', type: 'image/png', getAsFile: () => file }] } })
    await flushPromises()
    expect(api.ticket).toHaveBeenCalledWith(no, 'png', 1)
    api.claim.mockRejectedValueOnce(new Error('保存失败'))
    await wrapper.get('.shot-save').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('保存失败')
    expect(wrapper.text()).toContain('qr.png')
    await wrapper.get('.shot-save').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('保存成功')
    wrapper.unmount()
  })
  it('剪贴板没有图片时提示，不上传', async () => {
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await wrapper.get('.shot-paste').trigger('paste', { clipboardData: { items: [] } })
    expect(wrapper.text()).toContain('剪贴板中没有图片')
    expect(api.ticket).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('备注中粘贴普通文字不会提示图片错误', async () => {
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await wrapper.get('.shot-remark input').trigger('paste', { clipboardData: { items: [] } })
    expect(wrapper.text()).not.toContain('剪贴板中没有图片')
    wrapper.unmount()
  })
  it('右键菜单读取图片后使用相同的上传流程', async () => {
    const read = vi.fn().mockResolvedValue([{ types: ['image/png'], getType: vi.fn().mockResolvedValue(new Blob(['image'], { type: 'image/png' })) }])
    vi.stubGlobal('navigator', { ...navigator, clipboard: { read } })
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await wrapper.get('.shot-paste-wrap').trigger('contextmenu')
    await wrapper.get('.shot-paste-menu').trigger('click')
    await flushPromises()
    expect(read).toHaveBeenCalledOnce()
    expect(api.ticket).toHaveBeenCalledWith(no, 'png', 0)
    expect(api.put).toHaveBeenCalledOnce()
    expect(wrapper.text()).toContain('等待保存')
    wrapper.unmount()
    vi.unstubAllGlobals()
  })
  it('浏览器拒绝读取剪贴板时提示使用快捷键', async () => {
    vi.stubGlobal('navigator', { ...navigator, clipboard: { read: vi.fn().mockRejectedValue(new Error('denied')) } })
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await wrapper.get('.shot-paste-wrap').trigger('contextmenu')
    await wrapper.get('.shot-paste-menu').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('允许浏览器访问或使用快捷键')
    expect(api.ticket).not.toHaveBeenCalled()
    wrapper.unmount()
    vi.unstubAllGlobals()
  })
  it('订单截图达到上限时不申请上传，二维码不受此限制', async () => {
    api.fetch.mockResolvedValue({ items: Array.from({ length: 20 }, () => ({ img_type: 0 })) })
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await flushPromises()
    await wrapper.trigger('drop', { dataTransfer: { files: [image('order.png')] } })
    await flushPromises()
    expect(api.ticket).not.toHaveBeenCalled()
    expect(wrapper.text()).toContain('最多上传20张')
    await wrapper.get('input[value="1"]').setValue()
    await wrapper.trigger('drop', { dataTransfer: { files: [image('qr.png')] } })
    await flushPromises()
    expect(api.ticket).toHaveBeenCalledWith(no, 'png', 1)
    wrapper.unmount()
  })
  it('选择文件上传失败时显示原因，可重新选择同一文件', async () => {
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await flushPromises()
    const input = wrapper.get('input[type="file"]')
    const file = image('retry.png')
    Object.defineProperty(input.element, 'files', { configurable: true, value: [file] })
    api.put.mockRejectedValueOnce(new Error('上传失败'))
    await input.trigger('change')
    await flushPromises()
    expect(wrapper.text()).toContain('上传失败')
    expect(api.claim).not.toHaveBeenCalled()
    await input.trigger('change')
    await flushPromises()
    expect(wrapper.text()).toContain('retry.png')
    expect(api.ticket).toHaveBeenCalledTimes(2)
    wrapper.unmount()
  })
  it('上传中报告忙碌，卸载后不会开始上传下一张', async () => {
    let finish!: () => void
    api.put.mockReturnValueOnce(new Promise<void>((resolve) => { finish = resolve }))
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await flushPromises()
    await wrapper.trigger('drop', { dataTransfer: { files: [image('one.png'), image('two.png')] } })
    await flushPromises()
    expect(wrapper.emitted('busy-change')?.[0]).toEqual([true])
    expect(api.ticket).toHaveBeenCalledTimes(1)
    wrapper.unmount()
    finish()
    await flushPromises()
    expect(api.ticket).toHaveBeenCalledTimes(1)
    expect(api.put).toHaveBeenCalledTimes(1)
  })
  it('保存中卸载时不会继续认领下一张', async () => {
    api.ticket.mockResolvedValueOnce({ screenshot_id: 4, upload_url: '/upload' })
      .mockResolvedValueOnce({ screenshot_id: 5, upload_url: '/upload' })
    const wrapper = mount(V2ScreenshotUpload, { props: { orderNo: no } })
    await flushPromises()
    await wrapper.trigger('drop', { dataTransfer: { files: [image('one.png'), image('two.png')] } })
    await flushPromises()
    let finish!: () => void
    api.claim.mockReturnValueOnce(new Promise<void>((resolve) => { finish = resolve }))
    await wrapper.get('.shot-save').trigger('click')
    await flushPromises()
    expect(api.claim).toHaveBeenCalledTimes(1)
    const events = wrapper.emitted('busy-change') ?? []
    expect(events[events.length - 1]).toEqual([true])
    wrapper.unmount()
    finish()
    await flushPromises()
    expect(api.claim).toHaveBeenCalledTimes(1)
  })
})
