"""External platform paths shared by the WSGI entry and the HTTPS proxy."""
import argparse
import re


ROUTER_GROUPS = (
    "/api/business/order-push-settings",
    "/api/business/platform-auto-replies",
    "/api/business/platform-integrations",
    "/api/business/shop-bindings",
    "/api/business/tb-send-logs",
    "/api/business/xgj-bindings",
    "/api/business/xgj-shops",
)
ROUTER_FORMAT_PATH = re.compile(rf"^(?:{'|'.join(ROUTER_GROUPS)})[.][a-z0-9]+/?$")

SERVICE_GROUPS = (
    "/api/integration/v1",
    "/api/open",
    "/api/qqbot",
    "/api/taker",
    "/api/wechatmp",
    "/api/wecom",
    "/api/business/member/jidanpu-binding",
    "/api/business/member/upstream-jidanpu-binding",
    "/api/business/peer-bindings",
    "/api/business/peer-sync",
    "/api/business/platform-pushes",
    "/api/business/upstream-bindings",
    "/api/business/wxpusher-config",
    "/api/business/xgj",
) + ROUTER_GROUPS

EXACT_PATHS = (
    "/api/business/member/jidanpu-push-now/",
    "/api/business/member/jidanpu-sync-now/",
    "/api/business/member/upstream-jidanpu-sync-now/",
    "/api/business/order-qr/config/",
    "/api/business/read-platform-order/",
    "/api/business/upstream-price-change-logs/",
)
# Let Django keep handling missing slashes on API paths.
API_SLASH_REDIRECT_PATHS = tuple(path.rstrip("/") for path in EXACT_PATHS if path.endswith("/"))
PEER_BIND = "/api/business/peer-sync/bind/"


def serves_external_platform(path):
    return (
        path == "/healthz"
        or path in EXACT_PATHS
        or path in API_SLASH_REDIRECT_PATHS
        or any(path == group or path.startswith(group + "/") for group in SERVICE_GROUPS)
        or ROUTER_FORMAT_PATH.fullmatch(path) is not None
    )


def render_nginx(port):
    proxy = f"include proxy_params; proxy_pass http://127.0.0.1:{port};"
    lines = ["# Generated by external_platform_routes.py. Include in the site's HTTPS server."]
    lines.append(f"location = {PEER_BIND} {{ client_max_body_size 64k; {proxy} }}")
    for path in EXACT_PATHS + API_SLASH_REDIRECT_PATHS:
        lines.append(f"location = {path} {{ {proxy} }}")
    for group in SERVICE_GROUPS:
        lines.append(f"location = {group} {{ {proxy} }}")
        lines.append(f"location ^~ {group}/ {{ {proxy} }}")
    lines.append(f'location ~ "{ROUTER_FORMAT_PATH.pattern}" {{ {proxy} }}')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nginx-port", type=int, required=True)
    args = parser.parse_args()
    if not 1 <= args.nginx_port <= 65535:
        parser.error("--nginx-port must be between 1 and 65535")
    print(render_nginx(args.nginx_port), end="")
