"""Order and finance routes shared by the service and the proxy."""
import argparse
import re


ROUTER_ROUTE_GROUPS = ("orders", "performances", "wallet-transactions", "wallets", "withdrawals")
ROUTER_FORMAT_PATH = re.compile(
    rf"^/api/business/(?:{'|'.join(ROUTER_ROUTE_GROUPS)})[.][a-z0-9]+/?$",
)
SERVICE_ROUTE_GROUPS = (
    "/api/app/income",
    "/api/app/wallet",
    "/api/business/alipay-authorizations",
    "/api/business/approvals",
    "/api/business/business-report",
    "/api/business/deposit-rules",
    "/api/business/hall",
    "/api/business/hall-claim-target",
    "/api/business/my-orders",
    "/api/business/online-payroll",
    "/api/business/order-stats",
    "/api/business/screenshot-browser",
    "/api/business/settlements",
    "/api/business/support-stats",
    "/api/business/takers",
    "/api/business/xgj-receipts",
) + tuple("/api/business/" + group for group in ROUTER_ROUTE_GROUPS)

# Receipt sync starts a tenant-specific background task. Approval settings belong to Web.
RECEIPT_SYNC_ROUTE = "/api/business/orders/xgj-receipt-sync"
WEB_ROUTE_OVERRIDES = (
    RECEIPT_SYNC_ROUTE,
    RECEIPT_SYNC_ROUTE + "/",
    "/api/business/approvals/settings",
    "/api/business/approvals/settings/",
)
RECEIPT_SYNC_FORMAT = re.compile(rf"^{RECEIPT_SYNC_ROUTE}[.][a-z0-9]+/?$")


def serves_order_finance(path):
    return path == "/healthz" or (
        path not in WEB_ROUTE_OVERRIDES
        and RECEIPT_SYNC_FORMAT.fullmatch(path) is None
        and (
            any(path == group or path.startswith(group + "/") for group in SERVICE_ROUTE_GROUPS)
            or ROUTER_FORMAT_PATH.fullmatch(path) is not None
        )
    )


def _location(match, path, port):
    location = f"{match} {path}" if match else path
    return f"location {location} {{ include proxy_params; proxy_pass http://127.0.0.1:{port}; }}"


def render_nginx(service_port, web_port=8001):
    lines = ["# Generated by order_finance_routes.py. Include in the site's HTTPS server."]
    lines.extend(_location("=", path, web_port) for path in WEB_ROUTE_OVERRIDES)
    lines.append(_location("~", f'"{RECEIPT_SYNC_FORMAT.pattern}"', web_port))
    for group in SERVICE_ROUTE_GROUPS:
        lines.append(_location("=", group, service_port))
        # The receipt sync expression must run before choosing the orders prefix.
        match = "" if RECEIPT_SYNC_ROUTE.startswith(group + "/") else "^~"
        lines.append(_location(match, group + "/", service_port))
    lines.append(_location("~", f'"{ROUTER_FORMAT_PATH.pattern}"', service_port))
    return "\n".join(lines) + "\n"


def _network_port(value):
    port = int(value)
    if not 1 <= port <= 65535:
        raise argparse.ArgumentTypeError("port must be between 1 and 65535")
    return port


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nginx-port", type=_network_port, required=True)
    parser.add_argument("--web-port", type=_network_port, default=8001)
    args = parser.parse_args()
    if args.nginx_port == args.web_port:
        parser.error("the order-finance port must differ from the web port")
    print(render_nginx(args.nginx_port, args.web_port), end="")
